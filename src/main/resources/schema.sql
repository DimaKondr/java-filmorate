CREATE TABLE IF NOT EXISTS films (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(50) NOT NULL,
  description VARCHAR(200) NOT NULL,
  release_date DATE,
  duration BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) NOT NULL,
  login VARCHAR(50) NOT NULL,
  name VARCHAR(50) NOT NULL,
  birthday DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS ratings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(10) NOT NULL
);

CREATE TABLE IF NOT EXISTS genres (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS film_likes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  film_id BIGINT REFERENCES films(id),
  user_id BIGINT REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS age_ratings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  film_id BIGINT REFERENCES films(id),
  rating_id BIGINT REFERENCES ratings(id)
);

CREATE TABLE IF NOT EXISTS film_genres (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  film_id BIGINT REFERENCES films(id),
  genre_id BIGINT REFERENCES genres(id)
);

CREATE TABLE IF NOT EXISTS friendship (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES users(id),
  friend_id BIGINT REFERENCES users(id),
  status VARCHAR(12) DEFAULT 'UNCONFIRMED' CHECK (status IN ('UNCONFIRMED', 'CONFIRMED'))
);

-- таблица для реализации новой фичи add-feed
CREATE TABLE IF NOT EXISTS user_feeds (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp BIGINT NOT NULL,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    event_type VARCHAR(10) NOT NULL CHECK (event_type IN ('LIKE', 'REVIEW', 'FRIEND')),
    operation VARCHAR(10) NOT NULL CHECK (operation IN ('ADD', 'REMOVE', 'UPDATE')),
    entity_id BIGINT NOT NULL
);
-- индексы оптимизируют поиск по БД
CREATE INDEX IF NOT EXISTS idx_user_feeds_user_id ON user_feeds(user_id);
CREATE INDEX IF NOT EXISTS idx_user_feeds_timestamp ON user_feeds(timestamp);


CREATE TABLE IF NOT EXISTS reviews (
  reviewId BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  content VARCHAR NOT NULL,
  isPositive BOOLEAN NOT NULL,
  userId BIGINT REFERENCES users(id),
  filmId BIGINT REFERENCES films(id),
  useful BIGINT DEFAULT 0
);

CREATE TABLE IF NOT EXISTS reviews_likes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  review_id BIGINT REFERENCES reviews(reviewId) ON DELETE CASCADE,
  user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
  status VARCHAR(9) CHECK (status IN ('LIKED', 'DISLIKED')),
  UNIQUE(review_id, user_id)
);